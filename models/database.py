# ThreatIntel Model
# ─────────────────────────────────────────────────────────────────────────────
class ThreatIntel(Base):
    """Threat intelligence indicators (IPs, domains, hashes, URLs)."""
    __tablename__ = "threat_intel"
 
    id          = Column(Integer, primary_key=True, autoincrement=True)
    indicator   = Column(String(500), nullable=False, index=True)
    ioc_type    = Column(String(50))    # ip / domain / hash / url / email
    threat_type = Column(String(100))   # malware / c2 / phishing / scanner
    severity    = Column(String(20),  default="HIGH")
    confidence  = Column(Integer,     default=80)   # 0–100
    source      = Column(String(255))
    first_seen  = Column(DateTime, default=datetime.utcnow)
    last_seen   = Column(DateTime, default=datetime.utcnow)
    expires_at  = Column(DateTime)
    tags        = Column(JSON)
    description = Column(Text)
    active      = Column(Boolean, default=True)
 
    def to_dict(self):
        return {
            "id":          self.id,
            "indicator":   self.indicator,
            "ioc_type":    self.ioc_type,
            "threat_type": self.threat_type,
            "severity":    self.severity,
            "confidence":  self.confidence,
            "source":      self.source,
            "first_seen":  self.first_seen.isoformat() if self.first_seen else None,
            "last_seen":   self.last_seen.isoformat() if self.last_seen else None,
            "active":      self.active,
        }
 
 
